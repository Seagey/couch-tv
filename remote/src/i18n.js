const KEY = 'tv.lang';          // this phone's choice: 'auto' (same as the TV) or a language
const TV_KEY = 'tv.lang.tv';    // the TV's language, last read from the bridge
const read = (k) => { try { return localStorage.getItem(k); } catch { return null; } };
const write = (k, v) => { try { localStorage.setItem(k, v); } catch { /* private mode */ } };
const known = (id) => LANGS.some((l) => l.id === id);

function guess() {
  const n = (typeof navigator !== 'undefined' && navigator.language) || 'en';
  if (/^es-MX/i.test(n)) return 'es-MX';
  return /^es/i.test(n) ? 'es' : 'en';
}
function resolve() {
  const c = read(KEY);
  if (known(c)) return c;
  const tv = read(TV_KEY);
  return known(tv) ? tv : guess();
}

let lang = resolve();
const listeners = new Set();
function apply() {
  const next = resolve();
  if (next === lang) return;
  lang = next;
  try { document.documentElement.lang = locale(); } catch { /* no document */ }
  listeners.forEach((f) => f(lang));
}
try { document.documentElement.lang = LANGS.find((l) => l.id === lang).locale; } catch { /* no document */ }

export const choice = () => (known(read(KEY)) ? read(KEY) : 'auto');
export const locale = () => LANGS.find((l) => l.id === lang).locale;
export function setChoice(c) { write(KEY, known(c) ? c : 'auto'); apply(); }
export function setTvLang(id) { if (known(id)) { write(TV_KEY, id); apply(); } }

export function t(key, vars) {
  let s = (lang === 'es-MX' && S['es-MX'][key]) || (lang !== 'en' && S.es[key]) || S.en[key];
  if (s == null) s = key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}

// Re-renders the component (the whole app, from App) when the language changes.
export function useLang() {
  const [l, set] = useState(lang);
  useEffect(() => { listeners.add(set); return () => listeners.delete(set); }, []);
  return l;
}
