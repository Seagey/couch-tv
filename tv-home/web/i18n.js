  function find(id) { return LANGS.filter(function (l) { return l.id === id; })[0] || null; }

  function set(id) {
    lang = find(id) ? id : "en";
    try {
      var l = find(lang);
      document.documentElement.lang = l ? l.locale : "en";
      document.documentElement.dir = (l && l.dir) ? l.dir : "ltr";
    } catch (e) {}
    return lang;
  }

